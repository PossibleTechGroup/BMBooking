/**
 * Share content as a file (CSV)
 */
export const shareAsFile = async (content: string, filename: string) => {
  try {
    const fileUri = `${FileSystem.cacheDirectory}${filename}`;
    await FileSystem.writeAsStringAsync(fileUri, content);
    
    if (await Sharing.isAvailableAsync()) {
      await Sharing.shareAsync(fileUri, {
        mimeType: 'text/csv',
        dialogTitle: 'Export Schedule',
        UTI: 'public.comma-separated-values-text'
      });
    } else {
      // Fallback to native share text if file sharing not available
      Share.share({ message: content });
    }
  } catch (error) {
    console.error('Export error:', error);
    alert('Failed to export file');
  }
};

/**
 * Generic Native Share
 */
export const shareNative = (text: string) => {
  Share.share({
    message: text,
    title: 'Patient Schedule'
  });
};
